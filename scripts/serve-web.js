/* Dev server for web/.
 *
 * web/ is a static site with no build step, so the browser cannot read .env.
 * This server bridges that: it parses .env at startup and serves a generated
 * config.js, so the single place to configure a deploy is .env rather than a
 * checked-in JS file.
 *
 * It also proxies /api/* to LEVELUP_API_BASE. That proxy is not a convenience
 * — levelup_ai sends no CORS headers and answers the preflight with 405, so a
 * browser can only reach it same-origin.
 *
 *   node scripts/serve-web.js          # port from WEB_PORT, default 5500
 *   node scripts/serve-web.js 8080     # explicit port wins
 */

'use strict';

const http = require('http');
const https = require('https');
const fs = require('fs');
const path = require('path');
const { URL } = require('url');

const ROOT = path.resolve(__dirname, '..');
const WEB_DIR = path.join(ROOT, 'web');
const ENV_FILE = path.join(ROOT, '.env');

/* ------------------------------- .env ------------------------------- */

function loadEnv(file) {
  const out = {};
  let raw;
  try {
    raw = fs.readFileSync(file, 'utf8');
  } catch {
    console.warn(`[env] ${file} not found — falling back to process.env only`);
    return out;
  }
  for (const line of raw.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const env = { ...loadEnv(ENV_FILE), ...process.env };

const LEVELUP_API_BASE = (env.LEVELUP_API_BASE || '').replace(/\/+$/, '');
const NICHE_API_BASE = (env.NICHE_API_BASE || '').replace(/\/+$/, '');
const PORT = Number(process.argv[2] || env.WEB_PORT || 5500);

if (!LEVELUP_API_BASE) {
  console.error('[env] LEVELUP_API_BASE is empty — /api/* calls will fail. Set it in .env.');
}

/* Served in place of web/config.js. Both bases stay "" so the browser talks to
 * this server same-origin; the upstream host lives only on the proxy side. */
const GENERATED_CONFIG = `/* Generated by scripts/serve-web.js from .env — do not edit.
   Upstream: ${LEVELUP_API_BASE || '(unset)'} */
window.APP_CONFIG = {
  NICHE_API_BASE: "",
  PR_API_BASE: "",
};
`;

/* ------------------------------ serving ------------------------------ */

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.jsx': 'text/babel; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.ico': 'image/x-icon',
};

function proxy(req, res) {
  if (!LEVELUP_API_BASE) {
    res.writeHead(503, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'LEVELUP_API_BASE is not set in .env' }));
    return;
  }
  const target = new URL(req.url, LEVELUP_API_BASE);
  const headers = { ...req.headers, host: target.host };
  delete headers.origin;
  delete headers.referer;

  const transport = target.protocol === 'https:' ? https : http;
  const upstream = transport.request(
    {
      hostname: target.hostname,
      port: target.port || (target.protocol === 'https:' ? 443 : 80),
      path: target.pathname + target.search,
      method: req.method,
      headers,
    },
    (up) => {
      console.log(`[proxy] ${req.method} ${req.url} -> ${up.statusCode}`);
      res.writeHead(up.statusCode, up.headers);
      up.pipe(res);
    }
  );
  upstream.on('error', (err) => {
    console.error(`[proxy] ${req.method} ${req.url} FAILED: ${err.message}`);
    res.writeHead(502, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: `upstream unreachable: ${err.message}` }));
  });
  req.pipe(upstream);
}

function serveStatic(req, res) {
  const rel = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  const file = path.join(WEB_DIR, rel === '/' ? 'index.html' : rel);
  if (!file.startsWith(WEB_DIR)) {
    res.writeHead(403, { 'Content-Type': 'text/plain' });
    res.end('forbidden');
    return;
  }
  fs.readFile(file, (err, buf) => {
    if (err) {
      console.log(`[static] 404 ${rel}`);
      res.writeHead(404, { 'Content-Type': 'text/plain' });
      res.end('not found');
      return;
    }
    res.writeHead(200, {
      'Content-Type': MIME[path.extname(file)] || 'application/octet-stream',
      'Cache-Control': 'no-store',
    });
    res.end(buf);
  });
}

http
  .createServer((req, res) => {
    const pathname = new URL(req.url, 'http://localhost').pathname;
    if (pathname === '/config.js') {
      console.log('[config] generated from .env');
      res.writeHead(200, { 'Content-Type': MIME['.js'], 'Cache-Control': 'no-store' });
      res.end(GENERATED_CONFIG);
      return;
    }
    if (pathname.startsWith('/api/')) return proxy(req, res);
    return serveStatic(req, res);
  })
  .listen(PORT, () => {
    console.log(`web/      http://localhost:${PORT}`);
    console.log(`config.js generated from ${ENV_FILE}`);
    console.log(`/api/*    -> ${LEVELUP_API_BASE || '(LEVELUP_API_BASE unset)'}`);
    if (NICHE_API_BASE) console.log(`niche svc  ${NICHE_API_BASE} (configured, unused by web/)`);
  });
